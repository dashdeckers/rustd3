// Translates d3's own test files into the harness's Rust, offline:
//   node dev/harness/translate/translate.mjs           rewrites src/generated.rs and src/generated/
//   node dev/harness/translate/translate.mjs --check   exits 1 if they differ from a fresh translation
// Paths are relative to this file, so it runs from any directory.
import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { CATEGORIES, combine, rustStr, translateFile } from "./expr.mjs";
import array from "./rules/array.mjs";
import band from "./rules/band.mjs";
import binned from "./rules/binned.mjs";
import color from "./rules/color.mjs";
import ease from "./rules/ease.mjs";
import format from "./rules/format.mjs";
import interpolate from "./rules/interpolate.mjs";
import ordinal from "./rules/ordinal.mjs";
import path from "./rules/path.mjs";
import scale from "./rules/scale.mjs";
import shape from "./rules/shape.mjs";
import stats from "./rules/stats.mjs";
import zoom from "./rules/zoom.mjs";

const tests = (names) => names.map((n) => `${n}-test.js`);
// One generated module per suite: test files of one d3 package, translated
// in the listed order under the rules for that module's names. d3-zoom's
// zoom-test.js, zoom-events-test.js and zoom-callback-test.js drive the DOM
// and stand in Phase 10's skip table; rustd3-core's interact/zoom.rs ports
// zoom-test.js's numeric sequences.
const SUITES = [
  { suite: "path", package: "d3-path", files: tests(["path", "pathRound"]), rules: path },
  {
    suite: "ease",
    package: "d3-ease",
    files: tests(["back", "bounce", "circle", "cubic", "elastic", "exp", "linear", "poly", "quad", "sin"]),
    rules: ease,
  },
  {
    suite: "array",
    package: "d3-array",
    files: tests(["count", "min", "max", "extent", "sum", "mean", "variance", "deviation", "median", "quantile", "range", "bisect", "bin",
      "threshold/sturges", "threshold/scott", "threshold/freedmanDiaconic"]),
    rules: combine(stats, array),
  },
  { suite: "ticks", package: "d3-array", files: tests(["ticks", "tickIncrement", "tickStep", "nice"]), rules: array },
  {
    suite: "format",
    package: "d3-format",
    files: tests([
      "arabicLocale", "defaultLocale", "format", "format-trim", "format-type-%", "format-type-b", "format-type-c",
      "format-type-d", "format-type-e", "format-type-f", "format-type-g", "format-type-n", "format-type-none",
      "format-type-o", "format-type-p", "format-type-r", "format-type-s", "format-type-x", "formatPrefix",
      "formatSpecifier", "locale", "precisionFixed", "precisionPrefix", "precisionRound",
    ]),
    rules: format,
  },
  {
    suite: "scale",
    package: "d3-scale",
    files: tests(["linear", "pow", "sqrt", "log", "symlog", "tickFormat", "radial", "identity", "band", "point", "ordinal", "sequential", "diverging"]),
    rules: combine(binned, stats, band, ordinal, color, scale),
  },
  { suite: "interpolate", package: "d3-interpolate", files: tests(["number", "round", "rgb", "hsl", "hslLong", "lab", "hcl", "hclLong", "cubehelix", "cubehelixLong", "hue", "quantize", "piecewise"]), rules: combine(color, interpolate) },
  { suite: "color", package: "d3-color", files: tests(["color", "rgb", "hsl", "lab", "hcl", "cubehelix", "gray", "lch"]), rules: color },
  {
    suite: "shape",
    package: "d3-shape",
    files: [
      ...tests(["basis", "basisClosed", "basisOpen", "bumpX", "bumpY", "bundle", "cardinal", "cardinalClosed", "cardinalOpen",
        "catmullRom", "catmullRomClosed", "catmullRomOpen", "linear", "linearClosed", "monotoneX", "monotoneY", "natural",
        "step", "stepAfter", "stepBefore"].map((n) => `curve/${n}`)),
      ...tests(["line", "area"]),
    ],
    rules: shape,
  },
  { suite: "zoom", package: "d3-zoom", files: tests(["transform"]), rules: zoom },
];

const D3 = new URL("../d3/", import.meta.url);
const SRC = new URL("../src/", import.meta.url);
const HEADER = "// Generated by translate.mjs from d3's own test files. Do not edit.";

const args = process.argv.slice(2);
if (args.length > 1 || (args.length === 1 && args[0] !== "--check")) {
  console.error("usage: node dev/harness/translate/translate.mjs [--check]");
  process.exit(2);
}

const outputs = new Map([["generated.rs", topModule()]]);
for (const suite of SUITES) outputs.set(`generated/${suite.suite}.rs`, suiteModule(suite));

if (args[0] === "--check") {
  const problems = [];
  for (const [path, text] of outputs) {
    const disk = read(new URL(path, SRC));
    if (disk === null) problems.push(`missing: src/${path}`);
    else if (disk !== text) problems.push(`differs: src/${path}`);
  }
  for (const path of extras()) problems.push(`extra: src/${path}`);
  for (const p of problems) console.log(p);
  console.log(problems.length ? "the generated Rust is stale: rerun translate.mjs" : "the generated Rust is up to date");
  process.exit(problems.length ? 1 : 0);
}
mkdirSync(new URL("generated/", SRC), { recursive: true });
for (const [path, text] of outputs) writeFileSync(new URL(path, SRC), text);
for (const path of extras()) rmSync(new URL(path, SRC));

function topModule() {
  return [
    HEADER,
    "",
    "use crate::registry;",
    "",
    ...SUITES.map((s) => `mod ${s.suite};`),
    "",
    "pub const SUITES: &[registry::Suite] = &[",
    ...SUITES.map((s) => `    registry::Suite { name: ${rustStr(s.suite)}, tests: ${s.suite}::TESTS, asserts: ${s.suite}::ASSERTS },`),
    "];",
    "",
  ].join("\n");
}

function suiteModule({ suite, package: pkg, files, rules }) {
  const tests = [];
  const fns = new Map();
  for (const file of files) {
    const id = `${pkg}/test/${file}`;
    const result = translateFile(readFileSync(new URL(id.replaceAll("%", "%25"), D3), "utf8"), { id, rules });
    for (const [name, code] of result.fns) {
      if (fns.has(name) && fns.get(name) !== code) throw new Error(`suite ${suite}: two helpers named ${name}`);
      fns.set(name, code);
    }
    tests.push(...result.tests);
    summary(id, result.tests.flatMap((t) => t.asserts));
  }
  const assertion = (a, t) =>
    `    Assertion { id: ${rustStr(a.id)}, test: ${rustStr(t.name)}, skip: ${a.skip === null ? "None" : `Some(${rustStr(a.skip)})`} },`;
  return [
    HEADER,
    '#![allow(unused_mut, unused_parens, unused_assignments, clippy::all, reason = "generated from JavaScript")]',
    "",
    "use crate::prelude::*;",
    "use crate::registry::{Assertion, Test};",
    ...[...fns.values()].flatMap((code) => ["", code]),
    ...tests.flatMap((t, i) => ["", `fn t${i}() {   // ${t.name.replace(/\s+/g, " ")}`, ...t.lines.map((l) => `    ${l}`), "}"]),
    "",
    "pub const TESTS: &[Test] = &[",
    ...tests.map((t, i) => `    Test { name: ${rustStr(t.name)}, run: t${i} },`),
    "];",
    "",
    "pub const ASSERTS: &[Assertion] = &[",
    ...tests.flatMap((t) => t.asserts.map((a) => assertion(a, t))),
    "];",
    "",
  ].join("\n");
}

function summary(id, asserts) {
  const skipped = asserts.filter((a) => a.skip !== null);
  const by = CATEGORIES.map((c) => [c, skipped.filter((a) => a.skip.startsWith(`${c}:`)).length]).filter(([, n]) => n);
  const categories = by.length ? ` (${by.map(([c, n]) => `${c}: ${n}`).join(", ")})` : "";
  console.log(`${id}: ${asserts.length} assertions, ${asserts.length - skipped.length} translated, ${skipped.length} skipped${categories}`);
}

function read(url) {
  try {
    return readFileSync(url, "utf8");
  } catch (err) {
    if (err.code === "ENOENT") return null;
    throw err;
  }
}

function extras() {
  let names = [];
  try {
    names = readdirSync(new URL("generated/", SRC));
  } catch (err) {
    if (err.code !== "ENOENT") throw err;
  }
  return names.map((n) => `generated/${n}`).filter((p) => !outputs.has(p));
}
