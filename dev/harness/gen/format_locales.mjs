// Writes rustd3-core's bundled number locales from d3-format 3.1.2's locale
// tables, vendored under dev/harness/d3/:
//   node --import ./dev/harness/translate/d3-resolve.mjs dev/harness/gen/format_locales.mjs
// core/src/format/locales/<locale>.rs: one `format::Locale` constant each;
// core/src/format/locales.rs: their modules and a table of them;
// dev/fixtures/format_locales.json: d3's own formatLocale over a fixed probe
// list per locale, with en-IN and ar-001 as tables loaded at run time. Keys
// are sorted, every non-ASCII character in Rust source is a \u{…} escape,
// and nothing is printed on success.
import { readFileSync, writeFileSync } from "node:fs";
import { formatLocale } from "d3-format";

const TABLES = new URL("../d3/d3-format/locale/", import.meta.url);
const OUT = new URL("../../../core/src/format/", import.meta.url);
const FIXTURE = new URL("../../fixtures/format_locales.json", import.meta.url);
const HEADER = "// generated by dev/harness/gen/format_locales.mjs from d3-format 3.1.2";
const BUNDLED = {
  "de-DE": "German (Germany)",
  "en-US": "English (United States)",
  "es-ES": "Spanish (Spain)",
  "fr-FR": "French (France)",
  "it-IT": "Italian (Italy)",
  "ja-JP": "Japanese (Japan)",
  "nl-NL": "Dutch (Netherlands)",
  "pl-PL": "Polish (Poland)",
  "pt-BR": "Portuguese (Brazil)",
  "ru-RU": "Russian (Russia)",
  "zh-CN": "Chinese (China)",
};
const NOTES = { "en-US": " d3's default locale." };
const RUNTIME = ["ar-001", "en-IN"];
const PROBES = [[",.1f", 1234567.5], ["$,.2f", 1234.5], ["$,.2f", -1234.5], [".1%", 0.123], [",d", -12000], [".3s", 0.000042]];

/** `s` with every character outside printable ASCII as a Rust escape. */
const escape = (s) =>
  [...s].map((c) => (c === '"' || c === "\\" ? `\\${c}` : c >= " " && c <= "~" ? c : `\\u{${c.codePointAt(0).toString(16)}}`)).join("");
const str = (s) => `"${escape(s)}"`;
const constant = (name) => name.replace("-", "_").toUpperCase();
const module = (name) => name.replace("-", "_").toLowerCase();
const sorted = (o) => Object.fromEntries(Object.entries(o).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0)));
const read = (name) => sorted(JSON.parse(readFileSync(new URL(`${name}.json`, TABLES), "utf8")));
const write = (url, lines) => writeFileSync(url, [...lines, ""].join("\n"));

/** The fields of rustd3's Table for d3's definition, with d3's fallbacks (locale.js 13–20). */
function table(d) {
  const grouped = d.grouping !== undefined && d.thousands !== undefined;
  return [
    ["decimal", str(d.decimal ?? ".")],
    ["thousands", str(d.thousands ?? "")],
    ["grouping", `&[${grouped ? d.grouping.map(Number).join(", ") : ""}]`],
    ["currency", `[${(d.currency ?? ["", ""]).map(String).map(str).join(", ")}]`],
    ["numerals", d.numerals ? `Some(&[${d.numerals.map(String).map(str).join(", ")}])` : "None"],
    ["percent", str(d.percent ?? "%")],
    ["minus", str(d.minus ?? "−")],
    ["nan", str(d.nan ?? "NaN")],
    ["group_from", "1"],
  ];
}

const probes = (d) => {
  const locale = formatLocale(d);
  return PROBES.map(([spec, value]) => [spec, value, locale.format(spec)(value)]);
};

const names = Object.keys(BUNDLED);
/** A bundled locale's first two probes: `,.1f` of 1234567.5 and `$,.2f` of 1234.5. */
const shown = (name) => probes(read(name)).slice(0, 2).map(([, , out]) => out);
for (const name of names) {
  const [grouped, money] = shown(name);
  write(new URL(`locales/${module(name)}.rs`, OUT), [
    `${HEADER} locale/${name}.json. Do not edit.`,
    "",
    "use crate::format::Locale;",
    "use crate::format::locale::Table;",
    "",
    "impl Locale {",
    `    #[doc = ${str(`${BUNDLED[name]}: \`${grouped}\`, \`${money}\`.${NOTES[name] ?? ""}`)}]`,
    `    pub const ${constant(name)}: Locale = Locale::from_table(Table {`,
    ...table(read(name)).map(([k, v]) => `        ${k}: ${v},`),
    "    });",
    "}",
  ]);
}

write(new URL("locales.rs", OUT), [
  `${HEADER}. Do not edit.`,
  "",
  "//! d3-format's tables for en-US and the ten languages of the time tables,",
  "//! one constant of [`Locale`](super::Locale) each (non-ASCII characters",
  "//! below as Rust escapes):",
  "//!",
  "//! | Constant | Locale | `,.1f` of 1234567.5 | `$,.2f` of 1234.5 |",
  "//! | --- | --- | --- | --- |",
  ...names.map((name) => {
    const [grouped, money] = shown(name).map(escape);
    return `//! | [\`${constant(name)}\`](super::Locale::${constant(name)}) | ${BUNDLED[name]} | \`${grouped}\` | \`${money}\` |`;
  }),
  "",
  ...names.map((name) => `mod ${module(name)};`),
]);

const fixture = Object.fromEntries(
  [...names, ...RUNTIME].sort().map((name) => [name, { constant: BUNDLED[name] ? constant(name) : null, probes: probes(read(name)) }]),
);
write(FIXTURE, [JSON.stringify(fixture, null, 2)]);
