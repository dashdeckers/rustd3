// Writes rustd3-core's bundled time locales from d3-time-format 4.1.0's
// locale tables, vendored under dev/harness/d3/:
//   TZ=America/Los_Angeles node --import ./dev/harness/translate/d3-resolve.mjs dev/harness/gen/time_locales.mjs
// core/src/time/locales/<locale>.rs: one `time::Locale` constant each, the
// ISO ladder except en-US (d3's default, d3's ladder);
// core/src/time/locales.rs: their modules and a table of them;
// dev/fixtures/time_locales.json: d3's own timeFormatLocale over a fixed
// probe list on four instants in Los Angeles. Keys are sorted, every
// non-ASCII character in Rust source is a \u{…} escape, and nothing is
// printed on success.
import { readFileSync, writeFileSync } from "node:fs";
import { timeFormatLocale } from "d3-time-format";

if (new Date(2026, 0, 1).getTimezoneOffset() !== 480) throw new Error("run with TZ=America/Los_Angeles");
const TABLES = new URL("../d3/d3-time-format/locale/", import.meta.url);
const OUT = new URL("../../../core/src/time/", import.meta.url);
const FIXTURE = new URL("../../fixtures/time_locales.json", import.meta.url);
const HEADER = "// generated by dev/harness/gen/time_locales.mjs from d3-time-format 4.1.0";
const BUNDLED = {
  "de-DE": "German (Germany)",
  "en-US": "English (United States)",
  "es-ES": "Spanish (Spain)",
  "fr-FR": "French (France)",
  "it-IT": "Italian (Italy)",
  "ja-JP": "Japanese (Japan)",
  "nl-NL": "Dutch (Netherlands)",
  "pl-PL": "Polish (Poland)",
  "pt-BR": "Portuguese (Brazil)",
  "ru-RU": "Russian (Russia)",
  "zh-CN": "Chinese (China)",
};
const NOTES = { "en-US": " d3's default locale, with d3's tick-label ladder." };
// Local times in Los Angeles: a Saturday evening, New Year's midnight, a
// Tuesday morning in daylight saving time, a Sunday afternoon.
const INSTANTS = [new Date(2026, 2, 7, 23, 59, 30, 123), new Date(2026, 0, 1), new Date(2026, 6, 14, 9, 5, 1), new Date(2026, 9, 25, 14, 30)];
const SPECS = ["%c", "%x", "%X", "%a %A %b %B %p", "%x %X", "%a %d %b", "%B %b"];
const FIELDS = [["dateTime", "date_time"], ["date", "date"], ["time", "time"], ["periods", "periods"], ["days", "days"], ["shortDays", "short_days"], ["months", "months"], ["shortMonths", "short_months"]];

/** `s` with every character outside printable ASCII as a Rust escape. */
const escape = (s) =>
  [...s].map((c) => (c === '"' || c === "\\" ? `\\${c}` : c >= " " && c <= "~" ? c : `\\u{${c.codePointAt(0).toString(16)}}`)).join("");
const str = (s) => `"${escape(s)}"`;
const constant = (name) => name.replace("-", "_").toUpperCase();
const module = (name) => name.replace("-", "_").toLowerCase();
const read = (name) => JSON.parse(readFileSync(new URL(`${name}.json`, TABLES), "utf8"));
const write = (url, lines) => writeFileSync(url, [...lines, ""].join("\n"));
const value = (v) => (Array.isArray(v) ? `[${v.map(str).join(", ")}]` : str(v));
const shown = (name) => timeFormatLocale(read(name)).format("%c")(INSTANTS[0]);

const names = Object.keys(BUNDLED);
for (const name of names) {
  const d = read(name);
  write(new URL(`locales/${module(name)}.rs`, OUT), [
    `${HEADER} locale/${name}.json. Do not edit.`,
    "",
    "use crate::time::locale::Table;",
    "use crate::time::{Ladder, Locale};",
    "",
    "impl Locale {",
    `    #[doc = ${str(`${BUNDLED[name]}: \`%c\` writes \`${shown(name)}\`.${NOTES[name] ?? ""}`)}]`,
    `    pub const ${constant(name)}: Locale = Locale::from_table(Table {`,
    ...FIELDS.map(([key, field]) => `        ${field}: ${value(d[key])},`),
    `        ladder: Ladder::${name === "en-US" ? "D3" : "Iso"},`,
    "    });",
    "}",
  ]);
}

write(new URL("locales.rs", OUT), [
  `${HEADER}. Do not edit.`,
  "",
  "//! d3-time-format's tables for en-US and ten languages, one constant of",
  "//! [`Locale`](super::Locale) each, with `%c` of local 2026-03-07",
  "//! 23:59:30 (non-ASCII characters below as Rust escapes):",
  "//!",
  "//! | Constant | Locale | `%c` |",
  "//! | --- | --- | --- |",
  ...names.map((name) => `//! | [\`${constant(name)}\`](super::Locale::${constant(name)}) | ${BUNDLED[name]} | \`${escape(shown(name))}\` |`),
  "",
  ...names.map((name) => `mod ${module(name)};`),
]);

const probes = (name) => {
  const locale = timeFormatLocale(read(name));
  return SPECS.flatMap((spec) => INSTANTS.map((t) => [spec, t.toISOString(), locale.format(spec)(t)]));
};
const fixture = Object.fromEntries(names.map((name) => [name, { constant: constant(name), probes: probes(name) }]));
write(FIXTURE, [JSON.stringify(fixture, null, 2)]);
