// Writes rustd3-core's scheme tables from d3-scale-chromatic 3.1.0, vendored
// under dev/harness/d3/:
//   node --import ./dev/harness/translate/d3-resolve.mjs dev/harness/gen/scheme_tables.mjs
// core/src/scheme/stops.rs: the last stop row of each ColorBrewer scheme;
// core/src/scheme/{viridis,magma,inferno,plasma}.rs: the 256-entry tables
// and their ramps; core/src/scheme/categorical.rs: the categorical schemes
// beyond Category10 and Observable10. Output is sorted and reproduced byte for byte; nothing
// is printed on success.
import { writeFileSync } from "node:fs";
import { rgb } from "d3-color";
import * as chromatic from "d3-scale-chromatic";

const OUT = new URL("../../../core/src/scheme/", import.meta.url);
const HEADER = "// generated by dev/harness/gen/scheme_tables.mjs from d3-scale-chromatic 3.1.0. Do not edit.";
const RAMPS = ["Viridis", "Magma", "Inferno", "Plasma"];
const CATEGORICAL = ["Accent", "Dark2", "Paired", "Pastel1", "Pastel2", "Set1", "Set2", "Set3", "Tableau10"];
const COLORBREWER = Object.keys(chromatic)
  .filter((k) => k.startsWith("scheme") && !CATEGORICAL.includes(k.slice(6)) && Array.isArray(chromatic[k].at(-1)))
  .map((k) => k.slice(6));

/** d3's camel-case name as Rust's snake case, ColorBrewer's two-letter codes kept: PRGn → pr_gn. */
const snake = (name) => name.replace(/([a-z0-9])([A-Z])/g, "$1_$2").replace(/([A-Z])([A-Z][a-z])/g, "$1_$2").toLowerCase();
const hex = (color) => `Rgb::hex(0x${rgb(color).formatHex().slice(1)})`;
const table = (colors) => ["[", ...colors.map((c) => `    ${hex(c)},`), "];"];
const write = (name, lines) => writeFileSync(new URL(name, OUT), [HEADER, "", ...lines, ""].join("\n"));
const byName = (a, b) => (a < b ? -1 : a > b ? 1 : 0);

const rows = COLORBREWER.map((name) => [snake(name).toUpperCase(), name, chromatic[`scheme${name}`].at(-1)]).sort(([a], [b]) => byName(a, b));
write("stops.rs", [
  "//! The last stop row of each of d3's ColorBrewer schemes, which its",
  "//! sequential and diverging interpolators run a basis spline over.",
  "",
  "use crate::color::Rgb;",
  ...rows.flatMap(([rust, name, colors]) => [
    "",
    `/// d3's \`scheme${name}[${colors.length}]\`.`,
    `pub(crate) const ${rust}: [Rgb; ${colors.length}] = ${table(colors)[0]}`,
    ...table(colors).slice(1),
  ]),
]);

for (const name of RAMPS) {
  const f = chromatic[`interpolate${name}`];
  // d3's ramp reads entry floor(t·256): the middle of each entry's span reads it.
  const colors = Array.from({ length: 256 }, (_, i) => f((i + 0.5) / 256));
  const fn = snake(name);
  const shown = (t) => `assert_eq!(scheme::${fn}(${t.toFixed(1)}).format_hex(), "${rgb(f(t)).formatHex()}");`;
  write(`${fn}.rs`, [
    `//! d3's \`interpolate${name}\`: a 256-entry table and its ramp.`,
    "",
    "use crate::color::Rgb;",
    "",
    `/// d3's \`interpolate${name}\`: the entry \`floor(t·256)\` of its table,`,
    "/// clamped to the first and last; entry 0 for NaN, where d3 returns",
    "/// undefined.",
    "///",
    "/// ```",
    "/// use rustd3_core::scheme;",
    "///",
    ...[0, 0.5, 1].map((t) => `/// ${shown(t)}`),
    "/// ```",
    `#[doc(alias = "interpolate${name}")]`,
    "#[must_use]",
    `pub fn ${fn}(t: f64) -> Rgb {`,
    "    super::ramp(&TABLE, t)",
    "}",
    "",
    `/// The colors d3's ${fn} ramps over.`,
    `const TABLE: [Rgb; 256] = ${table(colors)[0]}`,
    ...table(colors).slice(1),
  ]);
}

write("categorical.rs", [
  "//! d3's categorical schemes beyond Category10 and Observable10:",
  "//! ColorBrewer's (Cynthia Brewer) and Tableau's.",
  "",
  "use crate::color::Rgb;",
  ...CATEGORICAL.map((name) => [snake(name).toUpperCase(), name]).sort(([a], [b]) => byName(a, b)).flatMap(([rust, name]) => {
    const colors = chromatic[`scheme${name}`];
    return [
      "",
      `/// d3's \`scheme${name}\`, ${colors.length} colors.`,
      `#[doc(alias = "scheme${name}")]`,
      `pub const ${rust}: [Rgb; ${colors.length}] = ${table(colors)[0]}`,
      ...table(colors).slice(1),
    ];
  }),
]);
